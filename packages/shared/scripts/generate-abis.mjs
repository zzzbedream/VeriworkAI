// Generates src/abis/generated/{veriWorkCore,agentRegistry,index}.ts from the Foundry artifacts in
// packages/contracts/out (run `forge build` first). Usage:
//   node scripts/generate-abis.mjs          write the files
//   node scripts/generate-abis.mjs --check  exit 1 when the committed files are stale (CI drift check)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const packageRoot = fileURLToPath(new URL('..', import.meta.url));
export const CONTRACTS_OUT = join(packageRoot, '..', 'contracts', 'out');
export const OUTPUT_DIR = join(packageRoot, 'src', 'abis', 'generated');

export const TARGETS = [
  {
    artifact: 'VeriWorkCore.sol/VeriWorkCore.json',
    file: 'veriWorkCore.ts',
    exportName: 'veriWorkCoreAbi',
  },
  {
    artifact: 'AgentRegistry.sol/AgentRegistry.json',
    file: 'agentRegistry.ts',
    exportName: 'agentRegistryAbi',
  },
];

/** Renders one ABI module; `source` documents where the ABI came from. */
export function renderAbiModule(exportName, abi, source) {
  return [
    `// GENERATED by packages/shared/scripts/generate-abis.mjs from ${source}.`,
    '// Do not edit by hand: run `pnpm abi:generate` after `forge build`.',
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;`,
    '',
  ].join('\n');
}

export function renderIndex(targets) {
  const lines = targets.map(
    (t) => `export { ${t.exportName} } from './${t.file.replace(/\.ts$/, '')}';`,
  );
  return [
    '// GENERATED by packages/shared/scripts/generate-abis.mjs. Do not edit by hand.',
    ...lines,
    '',
  ].join('\n');
}

function readArtifactAbi(artifactPath) {
  const json = JSON.parse(readFileSync(artifactPath, 'utf8'));
  if (!Array.isArray(json.abi)) throw new Error(`${artifactPath} has no "abi" array`);
  return json.abi;
}

export function buildOutputs(contractsOut = CONTRACTS_OUT) {
  const missing = TARGETS.map((t) => join(contractsOut, t.artifact)).filter(
    (path) => !existsSync(path),
  );
  if (missing.length > 0) {
    throw new Error(
      `Missing Foundry artifacts (run \`forge build\` in packages/contracts):\n  ${missing.join('\n  ')}`,
    );
  }
  const modules = TARGETS.map((t) => ({
    file: t.file,
    content: renderAbiModule(
      t.exportName,
      readArtifactAbi(join(contractsOut, t.artifact)),
      `packages/contracts/out/${t.artifact}`,
    ),
  }));
  return [...modules, { file: 'index.ts', content: renderIndex(TARGETS) }];
}

function main() {
  const check = process.argv.includes('--check');
  const outputs = buildOutputs();
  const stale = outputs.filter(({ file, content }) => {
    const target = join(OUTPUT_DIR, file);
    return !existsSync(target) || readFileSync(target, 'utf8') !== content;
  });
  if (check) {
    if (stale.length > 0) {
      process.stderr.write(
        `Stale generated ABIs: ${stale.map((o) => o.file).join(', ')}. Run pnpm abi:generate.\n`,
      );
      process.exit(1);
    }
    process.stdout.write('Generated ABIs are up to date.\n');
    return;
  }
  mkdirSync(OUTPUT_DIR, { recursive: true });
  for (const { file, content } of outputs) writeFileSync(join(OUTPUT_DIR, file), content);
  process.stdout.write(`Wrote ${outputs.length} files to ${OUTPUT_DIR}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  }
}
