import {
  hashCanonicalJson,
  LanguageCodeSchema,
  parseTaskInput,
  parseTaskOutput,
  TaskTypeSchema,
  type Hex,
  type TaskInput,
  type TaskOutput,
  type TaskType,
} from '@veriwork/shared';
import { z } from 'zod';
import rawDataset from './dataset.json' with { type: 'json' };

export interface DemoItem {
  readonly input: TaskInput;
  /** The pre-written AI draft: deliberately imperfect but plausible, so humans have work to do. */
  readonly draft: TaskOutput;
  /** What is wrong with the draft (maintainers' note, never shown to workers). */
  readonly flaw: string;
}

export interface DemoCampaign {
  readonly key: string;
  readonly taskType: TaskType;
  readonly title: string;
  readonly description: string;
  readonly instructions: string;
  readonly languages: readonly string[];
  readonly items: readonly DemoItem[];
}

export interface DemoDataset {
  /** `TaskItem.aiModel` of the curated drafts (honest: they were not generated by a model). */
  readonly model: string;
  readonly campaigns: readonly DemoCampaign[];
}

const Text = z.string().trim().min(1);

const DatasetSchema = z.strictObject({
  version: z.literal(1),
  model: Text.max(100),
  campaigns: z
    .array(
      z.strictObject({
        key: z.string().regex(/^[a-z0-9-]{3,40}$/),
        taskType: TaskTypeSchema,
        title: Text.max(200),
        description: Text.max(2_000),
        instructions: Text.max(4_000),
        languages: z.array(LanguageCodeSchema).max(8),
        items: z
          .array(z.strictObject({ input: z.unknown(), draft: z.unknown(), flaw: Text.max(500) }))
          .min(1)
          .max(100),
      }),
    )
    .min(1),
});

export class DatasetError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'DatasetError';
  }
}

function parseItem(
  taskType: TaskType,
  item: { readonly input: unknown; readonly draft: unknown; readonly flaw: string },
  where: string,
): DemoItem {
  const input = parseTaskInput(taskType, item.input);
  if (!input.ok) throw new DatasetError(`${where}: invalid input: ${input.error}`);
  const draft = parseTaskOutput(taskType, input.value, item.draft);
  if (!draft.ok) throw new DatasetError(`${where}: invalid draft: ${draft.error}`);
  return { input: input.value, draft: draft.value, flaw: item.flaw };
}

/** Validates a dataset document with the shared task schemas (every input and every draft). */
export function parseDemoDataset(value: unknown): DemoDataset {
  const parsed = DatasetSchema.safeParse(value);
  if (!parsed.success) throw new DatasetError(z.prettifyError(parsed.error));
  const keys = parsed.data.campaigns.map((campaign) => campaign.key);
  if (new Set(keys).size !== keys.length) throw new DatasetError('Duplicate campaign key');
  return {
    model: parsed.data.model,
    campaigns: parsed.data.campaigns.map((campaign) => ({
      ...campaign,
      items: campaign.items.map((item, index) =>
        parseItem(campaign.taskType, item, `${campaign.key}[${index}]`),
      ),
    })),
  };
}

/** Lookup key of an item: the task type and its normalized input, canonically hashed. */
export function demoItemKey(taskType: TaskType, input: TaskInput): Hex {
  return hashCanonicalJson({ taskType, input });
}

let cached: DemoDataset | null = null;

/** The curated demo dataset shipped with the worker (validated once). */
export function loadDemoDataset(): DemoDataset {
  cached ??= parseDemoDataset(rawDataset);
  return cached;
}
